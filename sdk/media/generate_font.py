"""H1Pixel16: lossless music UI subset of pinned Unifont pixel glyphs."""
from pathlib import Path
import argparse,gzip,hashlib,json,unicodedata
ROOT=Path(__file__).resolve().parent
def main():
    args=argparse.ArgumentParser()
    args.add_argument('--japanese',action='store_true')
    args.add_argument('--korean',action='store_true')
    args.add_argument('--output',type=Path)
    args.add_argument('--metadata',type=Path)
    options=args.parse_args()
    folder=ROOT/'fonts';source=folder/'unifont-16.0.04.hex.gz'
    provenance=json.loads((folder/'sources.json').read_text());digest=hashlib.sha256(source.read_bytes()).hexdigest()
    assert digest==provenance[source.name]['sha256']=='f9c8c7802453f47be02677176aeac2342ee96d354fad7a26cedcce48e68e1d9f'
    upstream={int(line.split(':')[0],16):line.split(':')[1] for line in gzip.decompress(source.read_bytes()).decode('ascii').splitlines()}
    chars=set(range(32,127))|{0x2026,0x25a1,0xfffd}
    for a in range(0xa1,0xf8):
        for b in range(0xa1,0xff):
            try:chars.add(ord(bytes([a,b]).decode('gb2312')))
            except UnicodeDecodeError:pass
    japanese=set()
    if options.japanese:
        japanese.update(range(0x3000,0x3100))
        japanese.update(range(0x31f0,0x3200))
        japanese.update(range(0xff61,0xffa0))
        for a in range(0xa1,0xff):
            for b in range(0xa1,0xff):
                try:japanese.add(ord(bytes((a,b)).decode('euc_jp')))
                except UnicodeDecodeError:pass
        chars|=japanese
    korean=set()
    if options.korean:
        for start,end in ((0x1100,0x1200),(0x3130,0x3190),(0xa960,0xa980),(0xac00,0xd7a4),(0xd7b0,0xd800)):
            korean.update(cp for cp in range(start,end) if unicodedata.category(chr(cp))!='Cn')
        chars|=korean
    if options.japanese or options.korean:chars.add(0x00b7)
    chars=sorted(chars);rows=[];widths=[]
    for cp in chars:
        data=bytes.fromhex(upstream[cp]);assert len(data) in (16,32),(cp,len(data))
        w=8 if len(data)==16 else 16;widths.append(w)
        rows.append([data[y]<<8 if w==8 else int.from_bytes(data[2*y:2*y+2],'big') for y in range(16)])
    assert all(widths[i]==8 for i in range(95))
    name='H1Pixel16'
    parts=[f'/* {name}, subset of GNU Unifont 16.0.04; unaltered pixel shapes.',
           ' * Roman Czyborra, Paul Hardy and Unifont contributors. SIL OFL-1.1.',
           ' * Generated by sdk/media/generate_font.py; see sdk/media/fonts/README.md. */',
           '#ifndef H1_FONT_H','#define H1_FONT_H','#include <stdint.h>',f'#define H1_FONT_COUNT {len(chars)}u',
           'static const uint16_t h1_font_cp[H1_FONT_COUNT]={']
    parts.extend(','.join(hex(cp) for cp in chars[i:i+24])+',' for i in range(0,len(chars),24));parts+=['};','static const uint8_t h1_font_width[H1_FONT_COUNT]={']
    parts.extend(','.join(str(w) for w in widths[i:i+48])+',' for i in range(0,len(chars),48));parts+=['};','static const uint16_t h1_font_rows[H1_FONT_COUNT][16]={']
    parts.extend('{'+','.join(hex(r) for r in row)+'},' for row in rows);parts+=['};','#endif']
    out=options.output or ROOT/'fonts/font16_data.h';out.write_text('\n'.join(parts)+'\n',encoding='ascii',newline='\n')
    proof=dict(name=name,source_sha256=digest,header_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),glyphs=len(chars),ascii_cell=[8,16],cjk_cell=[16,16],GB2312_complete=True,JIS_X_0208_complete=options.japanese,japanese_codepoints=len(japanese),Hangul_syllables_complete=options.korean,korean_codepoints=len(korean),lossless_pixel_shapes=True,packed_bytes=len(chars)*35)
    (options.metadata or ROOT/'fonts/font.json').write_text(json.dumps(proof,indent=2)+'\n');print(proof)
if __name__=='__main__':main()
